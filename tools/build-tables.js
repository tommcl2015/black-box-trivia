#!/usr/bin/env node
/* Generic fact-table question generator.
 * Each file in data/tables/*.js exports an array of tables:
 *   { pack: 'geo-currency', cat: 'geo', cols: ['country', 'currency', 'group', 'd'], rows: `a|b|c|2 ...`,
 *     qs: [ { q: 'What is the currency of {country}?', a: 'currency', group: 'group', dAdd: 0, unique: true } ] }
 * - {col} in q is replaced by that column's value.
 * - Wrong answers come from the same column in other rows, preferring rows with the same `group` value.
 * - unique: skip a row if the question text would be identical for rows with different answers
 *   (e.g. "The euro is the currency of which country?").
 * - years: true makes wrong answers nearby years instead.
 * - alt: column holding extra accepted answers separated by ';'.
 * - wrong: column holding hand-picked wrong answers separated by ';' (used instead of the automatic ones).
 * Output: data/new/4NN-table-<pack>.txt. Run: node tools/build-tables.js && npm run build:questions */
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, '..', 'data', 'tables');
const OUT = path.join(__dirname, '..', 'data', 'new');

let seed = 7041977;
const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const norm = s => String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/^the /, '').replace(/[^a-z0-9]/g, '');
const clean = s => String(s).replace(/\|/g, '/').replace(/;/g, ',');

function nearYears(y) {
  y = +y; const out = new Set();
  for (const d of shuffle([-1, 1, -2, 2, -3, 3, -5, 5, -10, 10])) { if (out.size < 3) out.add(String(y + d)); }
  return [...out];
}

let total = 0;
for (const f of fs.readdirSync(OUT)) if (/^4\d+-table-/.test(f)) fs.unlinkSync(path.join(OUT, f));
const files = fs.readdirSync(DIR).filter(f => f.endsWith('.js')).sort();
let n = 0;
for (const file of files) {
  const tables = require(path.join(DIR, file));
  for (const t of tables) {
    const rows = t.rows.trim().split('\n').map(l => l.split('|').map(s => s.trim())).filter(r => r.length > 1 && !r[0].startsWith('#'))
      .map(r => Object.fromEntries(t.cols.map((c, i) => [c, r[i] === undefined ? '' : r[i]])));
    for (const r of rows) for (const c of t.cols) if (r[c] === undefined) throw new Error(`${file}/${t.pack}: missing ${c}`);
    const lines = [];
    for (const spec of t.qs) {
      const fill = r => spec.q.replace(/\{(\w+)\}/g, (_, c) => r[c]);
      const byText = new Map();
      for (const r of rows) { const k = fill(r); if (!byText.has(k)) byText.set(k, new Set()); byText.get(k).add(norm(r[spec.a])); }
      for (const r of rows) {
        if (spec.when && !spec.when(r)) continue;
        const ans = r[spec.a]; if (!ans) continue;
        const text = fill(r);
        if (spec.unique && byText.get(text).size > 1) continue;
        let wrong;
        if (spec.years) wrong = nearYears(ans);
        else if (spec.wrong) wrong = shuffle((r[spec.wrong] || '').split(';').map(x => x.trim()).filter(x => x && norm(x) !== norm(ans))).slice(0, 3);
        else {
          const bad = new Set([norm(ans), ...(r[spec.alt] || '').split(';').map(norm)]);
          // never offer another correct answer for the same question text as a wrong option
          for (const o of rows) if (fill(o) === text) bad.add(norm(o[spec.a]));
          const pool = [...new Map(rows.filter(o => !bad.has(norm(o[spec.a])) && o[spec.a]).map(o => [norm(o[spec.a]), o])).values()];
          const gk = typeof spec.group === 'function' ? spec.group : (o => o[spec.group]);
          let same = spec.group ? pool.filter(o => gk(o) === gk(r)) : [];
          // near: prefer rows whose numeric column is closest (e.g. leaders from the same era)
          if (spec.near) same = (same.length >= 3 ? same : pool).slice().sort((x, y) => Math.abs(parseFloat(x[spec.near]) - parseFloat(r[spec.near])) - Math.abs(parseFloat(y[spec.near]) - parseFloat(r[spec.near]))).slice(0, 6);
          const pick = shuffle(same).concat(shuffle(pool.filter(o => !same.includes(o))));
          wrong = pick.slice(0, 3).map(o => o[spec.a]);
        }
        if (wrong.length < 3) continue;
        const d = Math.max(1, Math.min(5, (+r.d || t.d || 3) + (spec.dAdd || 0)));
        const alt = spec.alt ? (r[spec.alt] || '').split(';').filter(Boolean) : [];
        lines.push([t.cat, d, clean(text), clean(ans), wrong.map(clean).join(';'), alt.map(clean).join(';')].join('|'));
      }
    }
    const fileOut = path.join(OUT, `4${String(n++).padStart(3, '0')}-table-${t.pack}.txt`);
    fs.writeFileSync(fileOut, `# Generated by tools/build-tables.js from data/tables/${file} — edit the table, not this file\n${lines.join('\n')}\n`);
    total += lines.length;
    console.log(t.pack.padEnd(24), lines.length);
  }
}
console.log('total', total);
